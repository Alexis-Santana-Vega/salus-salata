-- 0008 · Catálogo de hospitales y sus contactos (paso 1.4).
-- La clave lleva el prefijo del estado (GTO-001, como en el Excel); el
-- servicio valida que el prefijo sea el estado de la colonia elegida.
-- La dirección es obligatoria y va normalizada (ASENTAMIENTO_ID).
-- La foto queda para la Fase 9 (ficha de hospital completa).

CREATE TABLE HOSPITAL (
  ID               BINARY(16)   NOT NULL,
  CLAVE            VARCHAR(10)  NOT NULL,
  NOMBRE           VARCHAR(150) CHARACTER SET UTF8 NOT NULL COLLATE UNICODE_CI_AI,
  TELEFONO         VARCHAR(20),
  CALLE            VARCHAR(120) NOT NULL,
  NUM_EXTERIOR     VARCHAR(20),
  NUM_INTERIOR     VARCHAR(20),
  ASENTAMIENTO_ID  BINARY(16)   NOT NULL,
  LATITUD          NUMERIC(9,6),
  LONGITUD         NUMERIC(9,6),
  LIGA_MAPA        VARCHAR(500),
  ACTIVO           BOOLEAN      DEFAULT TRUE NOT NULL,
  CREADO_EN        TIMESTAMP WITH TIME ZONE NOT NULL,
  ACTUALIZADO_EN   TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT PK_HOSPITAL PRIMARY KEY (ID),
  CONSTRAINT UQ_HOSPITAL_CLAVE UNIQUE (CLAVE),
  CONSTRAINT FK_HOSPITAL_ASENTAMIENTO FOREIGN KEY (ASENTAMIENTO_ID) REFERENCES ASENTAMIENTO (ID),
  CONSTRAINT CK_HOSPITAL_CLAVE CHECK (CLAVE SIMILAR TO '[A-Z]{2,5}\-[0-9]{3,4}' ESCAPE '\'),
  CONSTRAINT CK_HOSPITAL_LATITUD CHECK (LATITUD IS NULL OR LATITUD BETWEEN -90 AND 90),
  CONSTRAINT CK_HOSPITAL_LONGITUD CHECK (LONGITUD IS NULL OR LONGITUD BETWEEN -180 AND 180),
  CONSTRAINT CK_HOSPITAL_LIGA CHECK (LIGA_MAPA IS NULL OR LIGA_MAPA STARTING WITH 'https://')
);

CREATE INDEX IX_HOSPITAL_NOMBRE ON HOSPITAL (NOMBRE);

-- Personas en sitio para coordinar entregas y devoluciones. Se guardan junto
-- con el hospital (misma transacción) en el orden de captura.
CREATE TABLE CONTACTO_HOSPITAL (
  ID           BINARY(16)   NOT NULL,
  HOSPITAL_ID  BINARY(16)   NOT NULL,
  ORDEN        SMALLINT     NOT NULL,
  NOMBRE       VARCHAR(120) NOT NULL,
  PUESTO       VARCHAR(60),
  TELEFONO     VARCHAR(20),
  CONSTRAINT PK_CONTACTO_HOSPITAL PRIMARY KEY (ID),
  CONSTRAINT FK_CONTACTO_HOSPITAL FOREIGN KEY (HOSPITAL_ID) REFERENCES HOSPITAL (ID),
  CONSTRAINT UQ_CONTACTO_HOSPITAL_ORDEN UNIQUE (HOSPITAL_ID, ORDEN)
);
