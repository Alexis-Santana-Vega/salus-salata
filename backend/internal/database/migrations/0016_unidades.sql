-- 0016 · Unidades físicas de cada equipo (paso 1.7).
-- La clave (EQ-001-01) la genera el sistema con el consecutivo
-- "UNIDAD:<clave del equipo>" y no se reutiliza tras la baja lógica.
-- El número de serie es opcional y no se repite entre unidades activas.
-- Estado, hospital actual y ciclo de uso por unidad llegan en las Fases 2 y 4.
CREATE TABLE EQUIPO_UNIDAD (
  ID              BINARY(16)  NOT NULL,
  EQUIPO_ID       BINARY(16)  NOT NULL,
  CLAVE           VARCHAR(40) NOT NULL,
  NUM_SERIE       VARCHAR(60),
  FECHA_ALTA      DATE        NOT NULL,
  USOS_PREVIOS    INTEGER     DEFAULT 0 NOT NULL,
  ACTIVO          BOOLEAN     DEFAULT TRUE NOT NULL,
  CREADO_EN       TIMESTAMP WITH TIME ZONE NOT NULL,
  ACTUALIZADO_EN  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT PK_EQUIPO_UNIDAD PRIMARY KEY (ID),
  CONSTRAINT FK_EQUIPO_UNIDAD_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO (ID),
  CONSTRAINT UQ_EQUIPO_UNIDAD_CLAVE UNIQUE (CLAVE),
  CONSTRAINT CK_EQUIPO_UNIDAD_USOS CHECK (USOS_PREVIOS >= 0)
);

CREATE UNIQUE INDEX UQ_EQUIPO_UNIDAD_SERIE ON EQUIPO_UNIDAD (NUM_SERIE) WHERE ACTIVO = TRUE AND NUM_SERIE IS NOT NULL;
CREATE INDEX IX_EQUIPO_UNIDAD_EQUIPO ON EQUIPO_UNIDAD (EQUIPO_ID, ACTIVO);
