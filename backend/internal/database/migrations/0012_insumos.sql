-- 0012 · Claves de catálogo e insumos (paso 1.5).
--
-- CLAVE_CATALOGO reserva cada clave de equipo o insumo (RF-08): ambos la
-- registran aquí en la misma transacción, así la base impide que una clave
-- se repita entre los dos. Las claves no se liberan con la baja lógica.
-- Si se corrige una clave, el cambio se hace aquí y baja en cascada.
CREATE TABLE CLAVE_CATALOGO (
  CLAVE  VARCHAR(30) NOT NULL,
  TIPO   VARCHAR(10) NOT NULL,
  CONSTRAINT PK_CLAVE_CATALOGO PRIMARY KEY (CLAVE),
  CONSTRAINT CK_CLAVE_CATALOGO_TIPO CHECK (TIPO IN ('EQUIPO', 'INSUMO'))
);

-- STOCK_ACTUAL es la "entrada simple" de la Fase 1; en la Fase 7 se calculará
-- con los movimientos. Nunca negativo.
CREATE TABLE INSUMO (
  ID              BINARY(16)    NOT NULL,
  CLAVE           VARCHAR(30)   NOT NULL,
  DESCRIPCION     VARCHAR(200)  CHARACTER SET UTF8 NOT NULL COLLATE UNICODE_CI_AI,
  UNIDAD          VARCHAR(10)   NOT NULL,
  PRECIO          NUMERIC(12,2) NOT NULL,
  CODIGO_BARRAS   VARCHAR(64),
  STOCK_ACTUAL    INTEGER       DEFAULT 0 NOT NULL,
  STOCK_MINIMO    INTEGER       DEFAULT 0 NOT NULL,
  ACTIVO          BOOLEAN       DEFAULT TRUE NOT NULL,
  CREADO_EN       TIMESTAMP WITH TIME ZONE NOT NULL,
  ACTUALIZADO_EN  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT PK_INSUMO PRIMARY KEY (ID),
  CONSTRAINT UQ_INSUMO_CLAVE UNIQUE (CLAVE),
  CONSTRAINT FK_INSUMO_CLAVE FOREIGN KEY (CLAVE) REFERENCES CLAVE_CATALOGO (CLAVE) ON UPDATE CASCADE,
  CONSTRAINT UQ_INSUMO_CODIGO_BARRAS UNIQUE (CODIGO_BARRAS),
  CONSTRAINT CK_INSUMO_UNIDAD CHECK (UNIDAD IN ('PIEZA', 'CAJA', 'PAQUETE')),
  CONSTRAINT CK_INSUMO_PRECIO CHECK (PRECIO >= 0),
  CONSTRAINT CK_INSUMO_STOCK CHECK (STOCK_ACTUAL >= 0),
  CONSTRAINT CK_INSUMO_STOCK_MINIMO CHECK (STOCK_MINIMO >= 0)
);

CREATE INDEX IX_INSUMO_DESCRIPCION ON INSUMO (DESCRIPCION);
