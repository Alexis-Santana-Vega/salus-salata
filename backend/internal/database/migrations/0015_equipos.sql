-- 0015 · Equipo (modelo maestro) y sus tarifas de renta (paso 1.6).
-- La clave (EQ-001) la genera el sistema y se reserva en CLAVE_CATALOGO como
-- EQUIPO: no choca con ninguna clave de insumo. Las unidades llegan en el 1.7.
-- PURGA_CADA solo existe si el equipo requiere purga.
CREATE TABLE EQUIPO (
  ID              BINARY(16)   NOT NULL,
  CLAVE           VARCHAR(30)  NOT NULL,
  NOMBRE          VARCHAR(120) CHARACTER SET UTF8 NOT NULL COLLATE UNICODE_CI_AI,
  MARCA_MODELO    VARCHAR(120) CHARACTER SET UTF8 NOT NULL COLLATE UNICODE_CI_AI,
  CICLO_MAX       INTEGER      DEFAULT 50 NOT NULL,
  REQUIERE_PURGA  BOOLEAN      DEFAULT FALSE NOT NULL,
  PURGA_CADA      INTEGER,
  ACTIVO          BOOLEAN      DEFAULT TRUE NOT NULL,
  CREADO_EN       TIMESTAMP WITH TIME ZONE NOT NULL,
  ACTUALIZADO_EN  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT PK_EQUIPO PRIMARY KEY (ID),
  CONSTRAINT UQ_EQUIPO_CLAVE UNIQUE (CLAVE),
  CONSTRAINT FK_EQUIPO_CLAVE FOREIGN KEY (CLAVE) REFERENCES CLAVE_CATALOGO (CLAVE),
  CONSTRAINT CK_EQUIPO_CICLO CHECK (CICLO_MAX > 0),
  CONSTRAINT CK_EQUIPO_PURGA CHECK ((REQUIERE_PURGA = FALSE AND PURGA_CADA IS NULL)
                                 OR (REQUIERE_PURGA = TRUE AND PURGA_CADA > 0))
);

CREATE INDEX IX_EQUIPO_NOMBRE ON EQUIPO (NOMBRE);

-- Las tarifas no se sobrescriben: cambiar el costo agrega una fila vigente
-- desde ese día (historial de precios). La cotización usa la vigente en la
-- fecha de la cirugía. Un cambio el mismo día corrige la tarifa de ese día.
CREATE TABLE TARIFA_EQUIPO (
  ID             BINARY(16)    NOT NULL,
  EQUIPO_ID      BINARY(16)    NOT NULL,
  COSTO_HORA     NUMERIC(12,2) NOT NULL,
  VIGENTE_DESDE  DATE          NOT NULL,
  CREADO_EN      TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT PK_TARIFA_EQUIPO PRIMARY KEY (ID),
  CONSTRAINT FK_TARIFA_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO (ID),
  CONSTRAINT UQ_TARIFA_EQUIPO_FECHA UNIQUE (EQUIPO_ID, VIGENTE_DESDE),
  CONSTRAINT CK_TARIFA_COSTO CHECK (COSTO_HORA >= 0)
);
