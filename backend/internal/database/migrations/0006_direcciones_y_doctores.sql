-- 0006 · Catálogo de direcciones de México y catálogo de doctores (paso 1.3).
--
-- ESTADO: las 32 entidades (clave INEGI y abreviatura para la clave de
-- hospital, p. ej. GTO-001). MUNICIPIO (INEGI) y ASENTAMIENTO (colonias con su
-- código postal, SEPOMEX) se cargan al arrancar desde
-- internal/database/catalogos/direcciones.csv.gz (database.CargarDirecciones),
-- solo de los estados incluidos en ese archivo.
--
-- Una dirección guarda calle, números y el asentamiento: el C.P., la colonia,
-- el municipio y el estado salen del catálogo (sin texto libre que se desvíe).

CREATE DOMAIN D_CP AS CHAR(5)
  CHECK (VALUE IS NULL OR VALUE SIMILAR TO '[0-9]{5}');

CREATE TABLE ESTADO (
  ID           BINARY(16)  NOT NULL,
  CLAVE        CHAR(2)     NOT NULL,
  ABREVIATURA  VARCHAR(5)  NOT NULL,
  NOMBRE       VARCHAR(60) NOT NULL,
  CONSTRAINT PK_ESTADO PRIMARY KEY (ID),
  CONSTRAINT UQ_ESTADO_CLAVE UNIQUE (CLAVE),
  CONSTRAINT UQ_ESTADO_ABREVIATURA UNIQUE (ABREVIATURA)
);

CREATE TABLE MUNICIPIO (
  ID         BINARY(16)   NOT NULL,
  ESTADO_ID  BINARY(16)   NOT NULL,
  CLAVE      CHAR(3)      NOT NULL,
  NOMBRE     VARCHAR(120) CHARACTER SET UTF8 NOT NULL COLLATE UNICODE_CI_AI,
  CONSTRAINT PK_MUNICIPIO PRIMARY KEY (ID),
  CONSTRAINT FK_MUNICIPIO_ESTADO FOREIGN KEY (ESTADO_ID) REFERENCES ESTADO (ID),
  CONSTRAINT UQ_MUNICIPIO_CLAVE UNIQUE (ESTADO_ID, CLAVE)
);

-- CLAVE es id_asenta_cpcons de SEPOMEX (única dentro del municipio).
CREATE TABLE ASENTAMIENTO (
  ID            BINARY(16)   NOT NULL,
  MUNICIPIO_ID  BINARY(16)   NOT NULL,
  CLAVE         CHAR(4)      NOT NULL,
  CP            D_CP         NOT NULL,
  NOMBRE        VARCHAR(120) CHARACTER SET UTF8 NOT NULL COLLATE UNICODE_CI_AI,
  TIPO          VARCHAR(40)  NOT NULL,
  ZONA          VARCHAR(20),
  CIUDAD        VARCHAR(120),
  CONSTRAINT PK_ASENTAMIENTO PRIMARY KEY (ID),
  CONSTRAINT FK_ASENTAMIENTO_MUNICIPIO FOREIGN KEY (MUNICIPIO_ID) REFERENCES MUNICIPIO (ID),
  CONSTRAINT UQ_ASENTAMIENTO_CLAVE UNIQUE (MUNICIPIO_ID, CLAVE)
);

CREATE INDEX IX_ASENTAMIENTO_CP ON ASENTAMIENTO (CP);

-- NUMERO es opcional y, si existe, único para siempre (como una clave).
-- CORREO se guarda en minúsculas y es único solo entre los activos.
CREATE TABLE DOCTOR (
  ID               BINARY(16)   NOT NULL,
  NUMERO           VARCHAR(20),
  NOMBRE           VARCHAR(120) CHARACTER SET UTF8 NOT NULL COLLATE UNICODE_CI_AI,
  CORREO           VARCHAR(254) NOT NULL,
  TEL_PERSONAL     VARCHAR(20),
  TEL_CONSULTORIO  VARCHAR(20),
  CALLE            VARCHAR(120),
  NUM_EXTERIOR     VARCHAR(20),
  NUM_INTERIOR     VARCHAR(20),
  ASENTAMIENTO_ID  BINARY(16),
  ACTIVO           BOOLEAN      DEFAULT TRUE NOT NULL,
  CREADO_EN        TIMESTAMP WITH TIME ZONE NOT NULL,
  ACTUALIZADO_EN   TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT PK_DOCTOR PRIMARY KEY (ID),
  CONSTRAINT UQ_DOCTOR_NUMERO UNIQUE (NUMERO),
  CONSTRAINT FK_DOCTOR_ASENTAMIENTO FOREIGN KEY (ASENTAMIENTO_ID) REFERENCES ASENTAMIENTO (ID)
);

CREATE UNIQUE INDEX UQ_DOCTOR_CORREO ON DOCTOR (CORREO) WHERE ACTIVO = TRUE;
CREATE INDEX IX_DOCTOR_NOMBRE ON DOCTOR (NOMBRE);
